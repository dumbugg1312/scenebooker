'use strict';
/* Writes test/stubs/<module>.js for every module of SB.API.engine, from SB.API and test/stubs/_returns.js.
 * Run: node test/stubs/_gen.js          (add --check to only report: exit 1 if a stub file is out of date)
 * Owner: TEST. */
const vm = require('vm'), fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
['js/core/sb.js', 'js/core/enums.js', 'js/core/config.js'].forEach(function (rel) {
  vm.runInThisContext(fs.readFileSync(path.join(ROOT, rel), 'utf8'), { filename: rel });
});
const R = require('./_returns.js');
const check = process.argv.indexOf('--check') >= 0;
const engine = SB.API.engine;
const used = {};
let stale = 0, problems = [];

Object.keys(engine).forEach(function (mod) {
  const members = engine[mod].map(function (fn) {
    const key = mod + '.' + fn;
    if (!Object.prototype.hasOwnProperty.call(R, key)) { problems.push('no return value for ' + key); return null; }
    used[key] = true;
    return '    ' + fn + ': function () { return ' + R[key] + '; }';
  }).filter(Boolean);
  if (R.EXTRA && R.EXTRA[mod]) members.push('    ' + R.EXTRA[mod]);
  const text =
    '/* Stub of SB.' + mod + ' (test/stubs, generated by test/stubs/_gen.js from SB.API and _returns.js; do not edit).\n' +
    ' * Every function of the manifest returns a legal value of the documented shape. Replaced by the real file as soon as it exists. */\n' +
    "SB.module('" + mod + "', function (SB) {\n  'use strict';\n  return {\n" + members.join(',\n') + '\n  };\n});\n';
  const file = path.join(__dirname, mod.toLowerCase() + '.js');
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { stale++; problems.push('out of date: ' + file); }
  } else fs.writeFileSync(file, text);
});
Object.keys(R).forEach(function (k) {
  if (k !== 'EXTRA' && !used[k]) problems.push('_returns.js has an entry that is not in SB.API: ' + k);
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
console.log((check ? 'checked ' : 'wrote ') + Object.keys(engine).length + ' stubs');
